// Regenerates the metric glossary section of docs/api/analysis.md from
// src/analysis/glossary.js (the strings the UI shows), between the markers
// <!-- glossary:start --> and <!-- glossary:end -->.
//
// Run from app/:  node tools/analysis/make-glossary.mjs [--stdout]

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { GLOSSARY } from '../../src/analysis/glossary.js';

const DOC = new URL('../../docs/api/analysis.md', import.meta.url);
const LEVELS = [['node', 'Node measures'], ['network', 'Network measures'], ['group', 'Group measures'], ['ego', 'Ego measures'], ['uncertainty', 'Uncertainty'], ['time', 'Time'], ['content', 'Content']];
const esc = (s) => String(s).replace(/\|/g, '\\|');

let out = '<!-- glossary:start -->\n<!-- Generated by tools/analysis/make-glossary.mjs from src/analysis/glossary.js. Do not edit by hand. -->\n';
for (const [level, title] of LEVELS) {
  out += `\n### ${title}\n\n| Key | Name | Meaning | Formula / reference | Needs | Reliability |\n|---|---|---|---|---|---|\n`;
  for (const [key, g] of Object.entries(GLOSSARY)) {
    if (g.level !== level) continue;
    out += `| \`${key}\` | ${esc(g.label)} | ${esc(g.meaning)} | ${esc(g.formula)} | ${esc(g.needs)} | ${esc(g.reliability)} |\n`;
  }
}
out += '\n<!-- glossary:end -->';

// With --stdout, or when the doc does not exist yet, print the section instead.
const re = /<!-- glossary:start -->[\s\S]*<!-- glossary:end -->/;
if (process.argv.includes('--stdout') || !existsSync(DOC)) {
  process.stdout.write(out + '\n');
} else {
  const doc = readFileSync(DOC, 'utf8');
  if (!re.test(doc)) throw new Error('glossary markers not found in docs/api/analysis.md');
  writeFileSync(DOC, doc.replace(re, out));
  console.log('glossary written:', Object.keys(GLOSSARY).length, 'entries');
}
